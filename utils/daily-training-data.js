const DAILY_TOPIC_RECORD_KEY = 'dailyTopicRecord'
const DAILY_QUOTE_RECORD_KEY = 'dailyQuoteRecord'
const DAILY_TONGUE_TWISTER_RECORD_KEY = 'dailyTongueTwisterRecord'
const DAILY_ANONYMOUS_ID_KEY = 'dailyTrainingAnonymousId'

function pad(value) {
  return String(value).padStart(2, '0')
}

function getTodayText() {
  const date = new Date()
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
}

function safeGetStorage(key) {
  if (typeof wx === 'undefined' || !wx.getStorageSync) return null
  try {
    return wx.getStorageSync(key)
  } catch (err) {
    return null
  }
}

function safeSetStorage(key, value) {
  if (typeof wx === 'undefined' || !wx.setStorageSync) return
  try {
    wx.setStorageSync(key, value)
  } catch (err) {
    console.warn('[daily-training-data] storage write failed:', key, err)
  }
}

function getAnonymousId() {
  const userInfo = safeGetStorage('userInfo') || {}
  if (userInfo.openid) return userInfo.openid

  const cached = safeGetStorage(DAILY_ANONYMOUS_ID_KEY)
  if (cached) return cached

  const next = `anon_${Date.now()}_${Math.floor(Math.random() * 100000)}`
  safeSetStorage(DAILY_ANONYMOUS_ID_KEY, next)
  return next
}

function hashText(text) {
  let hash = 0
  for (let i = 0; i < text.length; i += 1) {
    hash = ((hash << 5) - hash) + text.charCodeAt(i)
    hash |= 0
  }
  return Math.abs(hash)
}

function clone(value) {
  return JSON.parse(JSON.stringify(value))
}

function findById(items, itemId) {
  return items.find(item => item.id === itemId) || null
}

function pickDailyItem(items, recordKey) {
  const today = getTodayText()
  const record = safeGetStorage(recordKey) || {}
  const cached = record.date === today ? findById(items, record.itemId) : null
  if (cached) return clone(cached)

  const index = hashText(`${today}:${recordKey}:${getAnonymousId()}`) % items.length
  const item = items[index]
  safeSetStorage(recordKey, { date: today, itemId: item.id })
  return clone(item)
}

function pickRandomItem(items, recordKey, currentId) {
  const today = getTodayText()
  const pool = items.filter(item => item.id !== currentId)
  const source = pool.length > 0 ? pool : items
  const item = source[Math.floor(Math.random() * source.length)]
  safeSetStorage(recordKey, { date: today, itemId: item.id })
  return clone(item)
}

function getDailyTopic() {
  return pickDailyItem(DAILY_TOPICS, DAILY_TOPIC_RECORD_KEY)
}

function getDailyQuote() {
  return pickDailyItem(DAILY_QUOTES, DAILY_QUOTE_RECORD_KEY)
}

function getDailyTongueTwister() {
  return pickDailyItem(TONGUE_TWISTERS, DAILY_TONGUE_TWISTER_RECORD_KEY)
}

function getRandomTopic(currentId) {
  return pickRandomItem(DAILY_TOPICS, DAILY_TOPIC_RECORD_KEY, currentId)
}

function getRandomQuote(currentId) {
  return pickRandomItem(DAILY_QUOTES, DAILY_QUOTE_RECORD_KEY, currentId)
}

function getRandomTongueTwister(currentId) {
  return pickRandomItem(TONGUE_TWISTERS, DAILY_TONGUE_TWISTER_RECORD_KEY, currentId)
}


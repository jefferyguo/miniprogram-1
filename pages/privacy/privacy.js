Page({
  onLoad(options = {}) {
    const type = String(options.type || 'privacy').trim()
    const isAgreement = type === 'agreement' || type === 'userAgreement'
    wx.setNavigationBarTitle({
      title: isAgreement ? '用户服务协议' : '隐私政策'
    })
    this.setData({
      sections: isAgreement ? USER_AGREEMENT_SECTIONS : PRIVACY_SECTIONS,
      showVoiceAgreement: !isAgreement,
      pageTitle: isAgreement ? '用户服务协议' : '隐私政策',
      pageDesc: isAgreement
        ? '请仔细阅读以下用户服务协议内容。'
        : '请了解我们如何收集、使用和保护与你使用本小程序有关的信息。'
    })
  },

  openVoiceprintAgreement() {
    wx.navigateTo({ url: '/pages/voiceprint-agreement/voiceprint-agreement' })
  }
})

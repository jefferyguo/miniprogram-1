test('预登记权益协调失败不会回滚已完成的手机号登录主链路', () => {
  const upsertStart = indexSource.indexOf('async function upsertPhoneAuthenticatedUser')
  const upsertEnd = indexSource.indexOf('async function reconcileBoundPhoneUser')
  const upsertSource = indexSource.slice(upsertStart, upsertEnd)
  const bindStart = indexSource.indexOf('async function bindPhoneInternal')
  const bindSource = indexSource.slice(bindStart, bindStart + 3600)
  assert.doesNotMatch(upsertSource, /resolvePendingPreauthorizationInTransaction/)
  assert.match(bindSource, /try\s*{[\s\S]*reconcileBoundPhoneUser\(nextUser\._id, phone\)[\s\S]*}\s*catch/)
  assert.match(bindSource, /phone login entitlement reconciliation deferred/)
})


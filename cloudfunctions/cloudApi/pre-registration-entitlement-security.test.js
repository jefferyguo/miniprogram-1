'use strict'

const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')

const indexSource = fs.readFileSync(path.join(__dirname, 'index.js'), 'utf8')
const adminServiceSource = fs.readFileSync(path.join(__dirname, 'user-membership-admin-service.js'), 'utf8')

test('预授权领取只挂在微信可信手机号链路且没有公开 claim action', () => {
  assert.match(indexSource, /cloud\.openapi\.phonenumber\.getPhoneNumber\(\{ code \}\)/)
  assert.match(indexSource, /bindPhoneInternal\(phone, event, wxContext\)/)
  assert.match(indexSource, /resolvePendingPreauthorizationInTransaction/)
  assert.doesNotMatch(indexSource, /case\s+['"]claimPendingEntitlement['"]/)
  assert.doesNotMatch(indexSource, /case\s+['"]claimPreRegistrationEntitlement['"]/)
})


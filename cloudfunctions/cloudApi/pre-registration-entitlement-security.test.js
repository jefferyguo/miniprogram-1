test('到期或遗留 pending 同步只由可信绑定用户、权限读取或管理员读取路径触发', () => {
  const accessStart = indexSource.indexOf('async function getCurrentAccess')
  const accessSource = indexSource.slice(accessStart, accessStart + 3200)
  const deferredStart = adminServiceSource.indexOf('async function reconcileMaturedDeferredUsers')
  const deferredEnd = adminServiceSource.indexOf('async function adminListUsers')
  const deferredSource = adminServiceSource.slice(deferredStart, deferredEnd)
  assert.match(accessSource, /shouldReconcilePreauthorization = user && trustedPhone/)
  assert.match(accessSource, /isDeferredPreauthorizationDue\(user\)/)
  assert.match(accessSource, /hasPendingPreauthorizationForPhone\(trustedPhone\)/)
  assert.match(accessSource, /reconcileBoundPhoneUser\(user\._id, trustedPhone\)/)
  assert.match(adminServiceSource, /async function reconcileMaturedDeferredUsers/)
  assert.match(adminServiceSource, /await reconcileMaturedDeferredUsers\(\)/)
  assert.match(adminServiceSource, /DEFERRED_RECONCILE_LIMIT = 20/)
  assert.doesNotMatch(deferredSource, /fetchAll/)
  assert.match(deferredSource, /preauthDeferredStartAt:\s*_\.lte\(dueAt\)/)
  assert.match(deferredSource, /orderBy\(['"]preauthDeferredStartAt['"],\s*['"]asc['"]\)/)
  assert.match(deferredSource, /limit\(DEFERRED_RECONCILE_LIMIT\)/)
  assert.doesNotMatch(indexSource, /case\s+['"]activateDeferredPreauthorization['"]/)
})

